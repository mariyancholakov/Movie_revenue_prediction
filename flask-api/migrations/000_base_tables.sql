-- The two tables the API caches predictions in, as they were before the
-- later migrations. Only needed for a fresh Supabase project; on the live one
-- they already exist and every statement here is a no-op.

-- One row per priced film: its prediction and, once the run is settled,
-- the actual (see 001). Upserts key on imdb_id; lookups go by tmdb_id.
CREATE TABLE IF NOT EXISTS movies (
    imdb_id           text PRIMARY KEY,
    tmdb_id           integer UNIQUE,
    title             text,
    opening_weekend   bigint,
    predicted_revenue bigint,
    decay_rate        double precision,
    half_life         double precision,
    -- true: a run being tracked; false: settled on the Ledger; null: an
    -- older film cached from a page visit, never tracked.
    is_in_theaters    boolean,
    last_scraped      timestamptz,
    created_at        timestamptz DEFAULT now()
);

-- A film's US weekend grosses for the decay chart. week counts from 0 (the
-- opening weekend). Replaced wholesale on each scrape.
CREATE TABLE IF NOT EXISTS weekly_gross (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imdb_id text REFERENCES movies (imdb_id),
    week    integer,
    gross   bigint
);
